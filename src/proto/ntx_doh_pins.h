/*
 * DoH SPKI pins — SHA-256(leaf SubjectPublicKeyInfo DER).
 *
 * Refresh:
 *   echo | openssl s_client -connect IP:443 -servername SNI -tls1_2 \
 *     -cipher ECDHE-RSA-AES128-GCM-SHA256 2>/dev/null \
 *     | openssl x509 -pubkey -noout \
 *     | openssl pkey -pubin -outform DER | sha256sum
 * (use ECDHE-ECDSA-… when leaf is ECC-only, e.g. Quad9)
 * Pin-sets: each host may carry up to NTX_DOH_PIN_MAX keys (npins); the leaf
 * matches ANY non-zero key. Rotation procedure: docs/network.md "Pin rotation".
 *
 * Pool policy: no Google / Cloudflare.
 * Order: Quad9 → OpenDNS → Control D → LibreDNS → UncensoredDNS → OpenBLD → DNSPod.
 * dns.sb was dropped when the client only spoke TLS 1.2; it has no pin now (TLS 1.3 needs its own SPKI pin).
 * tag: CLI compact dnsQ9 / dnsOD / dnsCD / dnsLD / dnsUC / dnsOB / dnsDP.
 *
 * Skipped from candidate list (2026-08-24 probe):
 *   147.135.76.183 LibreDNS — :443 closed
 *   119.29.29.29 / 182.254.116.116 DNSPod — no DoH on those IPs (use dig doh.pub)
 *   146.112.41.2 / .102 — OpenDNS IPs, not OpenBLD (ada.openbld.net = 45.144.49.133)
 */

#define NTX_DOH_PIN_MAX 8

typedef struct {
    uint32_t ip_be; /* network byte order */
    const char *sni;
    const char *path;
    const char *tag; /* CLI compact: "Q9", "OD", … */
    int npins;
    uint8_t pins[NTX_DOH_PIN_MAX][32];
} ntx_doh_pin_entry;

#define NTX_PIN32(a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,aa,ab,ac,ad,ae,af, \
                  b0,b1,b2,b3,b4,b5,b6,b7,b8,b9,ba,bb,bc,bd,be,bf) \
    { a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,aa,ab,ac,ad,ae,af, \
      b0,b1,b2,b3,b4,b5,b6,b7,b8,b9,ba,bb,bc,bd,be,bf }

#define NTX_IP4(a, b, c, d) \
    ((uint32_t)(a) | ((uint32_t)(b) << 8) | ((uint32_t)(c) << 16) | ((uint32_t)(d) << 24))

