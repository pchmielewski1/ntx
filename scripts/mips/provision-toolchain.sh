#!/usr/bin/env bash
#
# Provision the mipsel (mips32r2, 24kc) musl soft-float cross toolchain on an
# x86_64 host by extracting the official OpenWrt SDK (prebuilt toolchain, no
# compilation). Target: MT7621 (MIPS 24Kc, no FPU) — soft-float ABI is mandatory.
#
# Bootlin toolchains are NOT usable here: every mips32el musl fragment is
# hard-float (BR2_MIPS_SOFT_FLOAT unset) and would SIGILL on MT7621.
#
# Idempotent: if the wrapper already exists, this script is a no-op.
#
# Interface consumed by Task 3 (MIPS_CC default):
#   ~/toolchains/mipsel-linux-musl/bin/mipsel-linux-musl-gcc
set -euo pipefail

SDK_URL="https://downloads.openwrt.org/releases/23.05.5/targets/ramips/mt7621/openwrt-sdk-23.05.5-ramips-mt7621_gcc-12.3.0_musl.Linux-x86_64.tar.xz"
SDK_SHA256="97ac89bcd590cf882bad8e027d893ab073959628b69e9e43829a2ccfb1e11e29"
SDK_NAME="openwrt-sdk-23.05.5-ramips-mt7621"
SDK_TARBALL="${SDK_NAME}_gcc-12.3.0_musl.Linux-x86_64.tar.xz"

TOOLCHAINS_DIR="$HOME/toolchains"
SDK_DIR="$TOOLCHAINS_DIR/$SDK_NAME"
# The tarball unpacks into a directory carrying the gcc/musl/host suffix.
EXTRACTED_DIR="$TOOLCHAINS_DIR/${SDK_NAME}_gcc-12.3.0_musl.Linux-x86_64"
TOOLCHAIN_BIN_GLOB="$SDK_DIR/staging_dir/toolchain-mipsel_24kc_gcc-*/bin"
WRAPPER_DIR="$TOOLCHAINS_DIR/mipsel-linux-musl/bin"
WRAPPER="$WRAPPER_DIR/mipsel-linux-musl-gcc"

# --- idempotent short-circuit -------------------------------------------------
if [ -x "$WRAPPER" ]; then
    echo "[provision] wrapper already present: $WRAPPER — nothing to do"
    exit 0
fi

# --- disk guard: >= 3 GB free on / --------------------------------------------
free_kb=$(df -P / | awk 'NR==2 {print $4}')
if [ "$free_kb" -lt $((3 * 1024 * 1024)) ]; then
    echo "[provision] ERROR: need >= 3 GB free on / (have $((free_kb / 1024)) MB). Abort." >&2
    exit 1
fi

mkdir -p "$TOOLCHAINS_DIR"

# --- download + verify ---------------------------------------------------------
if [ ! -f "$TOOLCHAINS_DIR/$SDK_TARBALL" ]; then
    echo "[provision] downloading $SDK_URL ..."
    curl -fL --retry 3 -o "$TOOLCHAINS_DIR/$SDK_TARBALL.part" "$SDK_URL"
    mv "$TOOLCHAINS_DIR/$SDK_TARBALL.part" "$TOOLCHAINS_DIR/$SDK_TARBALL"
fi

echo "[provision] verifying sha256 ..."
actual=$(sha256sum "$TOOLCHAINS_DIR/$SDK_TARBALL" | awk '{print $1}')
if [ "$actual" != "$SDK_SHA256" ]; then
    echo "[provision] ERROR: sha256 mismatch" >&2
    echo "  expected: $SDK_SHA256" >&2
    echo "  actual:   $actual" >&2
    rm -f "$TOOLCHAINS_DIR/$SDK_TARBALL"
    exit 1
fi

# --- extract (tarball unpacks into a dir with the gcc/host suffix) --------------
if [ ! -d "$SDK_DIR" ]; then
    if [ ! -d "$EXTRACTED_DIR" ]; then
        echo "[provision] extracting ..."
        tar -xf "$TOOLCHAINS_DIR/$SDK_TARBALL" -C "$TOOLCHAINS_DIR"
    fi
    if [ ! -d "$SDK_DIR" ]; then
        mv "$EXTRACTED_DIR" "$SDK_DIR"
    fi
fi

# --- locate the prebuilt SDK gcc ------------------------------------------------
shopt -s nullglob
# unquoted on purpose: the gcc-version wildcard in TOOLCHAIN_BIN_GLOB must expand
candidates=($TOOLCHAIN_BIN_GLOB/mipsel-openwrt-linux-musl-gcc)
shopt -u nullglob
sdk_gcc=""
for c in "${candidates[@]}"; do
    if [ -x "$c" ]; then sdk_gcc="$c"; break; fi
done
if [ -z "$sdk_gcc" ]; then
    echo "[provision] ERROR: mipsel-openwrt-linux-musl-gcc not found under $TOOLCHAIN_BIN_GLOB" >&2
    exit 1
fi

# --- thin wrapper: the stable interface for the build system --------------------
mkdir -p "$WRAPPER_DIR"
staging_dir=$(dirname "${sdk_gcc%/bin/*}")
printf '#!/bin/sh\n# Generated by scripts/mips/provision-toolchain.sh — execs the OpenWrt SDK gcc.\nSDK_GCC="%s"\n[ -n "${STAGING_DIR:-}" ] || export STAGING_DIR="%s"\nexec "$SDK_GCC" "$@"\n' "$sdk_gcc" "$staging_dir" > "$WRAPPER".tmp
chmod +x "$WRAPPER".tmp
mv "$WRAPPER".tmp "$WRAPPER"

echo "[provision] done: $WRAPPER -> $sdk_gcc"
