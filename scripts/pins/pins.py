#!/usr/bin/env python3
"""Share-tracker key gate for ntx --share (design §6.2, plan Task C4).

  check   verify every host of the built-in table; exit 1 on a blocking row.
  update  same, then append verified new keys to the generated block of
          src/proto/ntx_share_trackers.c and to pins.txt, and print the diff.

Report rows are `<host> <OK|NEW-KEY|WEBPKI-FAIL|FULL-SCRAPE> <detail>` (plus
UNREACHABLE for a host that did not answer). Exit 0 = OK or warnings only,
exit 1 = a row of the §6.2 blocking table (new key, bad WebPKI, full scrape,
or fewer qualified hosts than NTX_SHARE_MIN_TRACKERS).

`--offline-fixture DIR` replays recorded probe results from DIR/fixture.txt so
`make test` never touches the network; format in scripts/pins/README.md. Only
`make pins-check` / `make pins-update` (i.e. a human or the release gate) run
live. Requires python3 + the openssl CLI.
"""

import argparse
import difflib
import hashlib
import os
import re
import ssl
import subprocess
import sys
import urllib.request

MAX_PINS = 4              # NTX_HTTPS_PIN_MAX (src/proto/ntx_https_pins.h)
MIN_HOSTS = 2             # NTX_SHARE_MIN_TRACKERS (src/proto/ntx_share_trackers.h)
DEFAULT_TABLE = "src/proto/ntx_share_trackers.c"
BEGIN = "/* BEGIN GENERATED"
END = "/* END GENERATED"
TIMEOUT = 20              # per openssl attempt / per scrape GET; §6.2 allows 3 tries

ROWS_RE = re.compile(r'\{\s*"(?P<url>[^"]*)"\s*,\s*"(?P<host>[^"]*)"'
                     r"\s*,\s*\{(?P<pins>[^{}]*)\}\s*\}")
VERIFY_RE = re.compile(r"Verify return code:\s*(\d+)")
CERT_RE = re.compile(r"-----BEGIN CERTIFICATE-----[^-]*-----END CERTIFICATE-----", re.S)


def pin_from_pem(pem):
    """leaf certificate -> sha256 of its SPKI DER, the pins.txt recipe."""
    der = subprocess.run(["openssl", "x509", "-pubkey", "-noout", "-outform", "DER"],
                         input=pem.encode(), capture_output=True).stdout
    return hashlib.sha256(der).hexdigest() if der else None


def read_table(path):
    src = open(path, encoding="utf-8").read()
    try:
        a, b = src.index(BEGIN), src.index(END)
    except ValueError:
        sys.exit("pins: %s has no `%s` block" % (path, BEGIN))
    rows = []
    for m in ROWS_RE.finditer(src[a:b]):
        cells = [t.strip().strip('"') for t in m.group("pins").split(",")]
        rows.append({"url": m.group("url"), "host": m.group("host"),
                     "pins": [c for c in cells if c and c != "0"]})
    return src, a, b, rows


def render_rows(rows):
    out = ["static const strk_raw strk_raw_tab[] = {"]
    for r in rows:
        cells = ['"%s"' % p for p in r["pins"][:MAX_PINS]]
        cells += ["0"] * (MAX_PINS - len(cells))
        out.append('    {"%s", "%s",' % (r["url"], r["host"]))
        out.append("     {%s}}," % ", ".join(cells))
    out.append("};")
    return "\n".join(out) + "\n"


def unified(path, before, after):
    if before == after:
        return ""
    return "".join(l + "\n" for l in difflib.unified_diff(
        before.splitlines(), after.splitlines(), path, path, lineterm=""))


def write_table(path, src, a, b, rows):
    """Rewrite only the generated block; returns the diff (empty = no change)."""
    if not rows:
        return "pins: refusing to write an empty tracker block (fail closed)\n"
    start = src.index("\n", a) + 1
    end = src.rindex("\n", 0, b) + 1
    after = src[:start] + render_rows(rows) + src[end:]
    diff = unified(path, src, after)
    if diff:
        open(path, "w", encoding="utf-8").write(after)
    return diff


def write_pins_txt(path, rows):
    """Regenerate the share rows of pins.txt; DoH rows and comments are kept."""
    try:
        before = open(path, encoding="utf-8").read()
    except OSError:
        before = ""
    hosts = {r["host"] for r in rows}
    keep = [l for l in before.splitlines()
            if not (l.split() and not l.startswith("#") and l.split()[0] in hosts)]
    while keep and not keep[-1].strip():
        keep.pop()
    keep += ["", "# Share trackers (ntx --share) — regenerated by `make pins-update`."]
    for r in rows:
        for p in r["pins"]:
            keep.append("%-34s%s" % (r["host"], p))
    after = "\n".join(keep) + "\n"
    diff = unified(path, before, after)
    if diff:
        open(path, "w", encoding="utf-8").write(after)
    return diff


def is_full_scrape(body):
    # ponytail: substring test, not a bencode decode — an empty `d5:filesde` and
    # an error page both pass. Upgrade path: decode with src/proto/ntx_bencode.c.
    return body is not None and b"files" in body and len(body) > 20


def probe_live(row, tries):
    """One host, up to `tries` openssl attempts (§6.2); scrape once on success."""
    host, detail = row["host"], "no response"
    for _ in range(max(1, tries)):
        try:
            p = subprocess.run(["openssl", "s_client", "-connect", host + ":443",
                                "-servername", host, "-verify_return_error",
                                "-verify_hostname", host, "-showcerts"],
                               input=b"", capture_output=True, timeout=TIMEOUT)
        except (OSError, subprocess.TimeoutExpired) as e:
            detail = str(e)
            continue
        out = (p.stdout + p.stderr).decode("utf-8", "replace")
        v, c = VERIFY_RE.search(out), CERT_RE.search(out)
        if v and c:
            return {"verify": int(v.group(1)), "pem": c.group(0),
                    "scrape": scrape_live(row)}
        detail = "no certificate" if not c else "no verify line"
    return {"verify": None, "pem": None, "scrape": None, "detail": detail}


def scrape_live(row):
    """GET <announce dir>/scrape with the system CA store; None = error/empty."""
    try:
        with urllib.request.urlopen(row["url"].rsplit("/", 1)[0] + "/scrape",
                                    timeout=TIMEOUT,
                                    context=ssl.create_default_context()) as r:
            return r.read()
    except Exception:
        return None


def classify(row, probe):
    if probe.get("pem") is None or probe.get("verify") is None:
        return "UNREACHABLE", probe.get("detail", "no response")
    if probe["verify"] != 0:
        return "WEBPKI-FAIL", "verify return code %d" % probe["verify"]
    pin = pin_from_pem(probe["pem"])
    if pin is None:
        return "WEBPKI-FAIL", "leaf SPKI unreadable"
    if is_full_scrape(probe.get("scrape")):
        return "FULL-SCRAPE", "%d bytes from /scrape" % len(probe["scrape"])
    return ("OK", pin) if pin in row["pins"] else ("NEW-KEY", pin)


def pem_from_b64(b64):
    return "-----BEGIN CERTIFICATE-----\n%s\n-----END CERTIFICATE-----\n" % \
        "\n".join(b64[i:i + 64] for i in range(0, len(b64), 64))


def load_fixture(dirpath):
    rows, probes = [], {}
    with open(os.path.join(dirpath, "fixture.txt"), encoding="utf-8") as f:
        for line in f:
            t = line.split()
            if not t or t[0].startswith("#"):
                continue
            if t[0] == "HOST" and len(t) >= 3:
                rows.append({"url": t[1], "host": t[2], "pins": t[3:]})
            elif t[0] == "PROBE" and len(t) >= 3:
                p = probes.setdefault(t[1], {"verify": None, "pem": None,
                                             "scrape": None, "detail": "no probe"})
                if t[2] == "verify":
                    p["verify"] = int(t[3])
                elif t[2] == "cert":
                    p["pem"] = pem_from_b64(t[3])
                elif t[2] == "unreachable":
                    p["detail"] = t[3] if len(t) > 3 else "timeout"
                elif t[2] == "scrape":
                    p["scrape"] = (t[3] if len(t) > 3 else "").encode()
    return rows, probes


def apply_update(rows, results):
    """Keep the old pin, add the verified new one; drop the oldest at MAX_PINS."""
    changed = False
    for r in rows:
        st, detail = results[r["host"]]
        if st != "NEW-KEY" or detail in r["pins"]:
            continue
        if len(r["pins"]) >= MAX_PINS:
            r["pins"].pop(0)
        r["pins"].append(detail)
        changed = True
    return changed


def main(argv):
    ap = argparse.ArgumentParser(description="share tracker key gate (§6.2)")
    ap.add_argument("cmd", choices=["check", "update"])
    ap.add_argument("--offline-fixture", metavar="DIR",
                    help="replay DIR/fixture.txt instead of connecting")
    ap.add_argument("--tries", type=int, default=3, help="openssl attempts per host")
    ap.add_argument("--trackers", default=DEFAULT_TABLE)
    ap.add_argument("--pins-txt", default="pins.txt")
    a = ap.parse_args(argv)

    if a.offline_fixture:
        rows, probes = load_fixture(a.offline_fixture)
        where = a.offline_fixture
        # update rewrites the generated block, so it still needs the real source
        if a.cmd == "update":
            src, tab_a, tab_b, _ = read_table(a.trackers)
        else:
            src, tab_a, tab_b = None, 0, 0
    else:
        src, tab_a, tab_b, rows = read_table(a.trackers)
        probes = None
        where = a.trackers
    if not rows:
        sys.exit("pins: no pinned hosts in %s" % where)

    results = {}
    for row in rows:
        probe = probes[row["host"]] if probes else probe_live(row, a.tries)
        results[row["host"]] = classify(row, probe)
    for row in rows:
        print("%s %s %s" % (row["host"], results[row["host"]][0],
                            results[row["host"]][1]))

    qualified = [r for r in rows if results[r["host"]][0] == "OK" or
                 (a.cmd == "update" and results[r["host"]][0] == "NEW-KEY")]
    # §6.2: a verified new key blocks `check` (pins-update is the fix) but not
    # `update`, which is the command that absorbs it.
    blocking = {s for s in (results[r["host"]][0] for r in rows)
                if s in ("WEBPKI-FAIL", "FULL-SCRAPE")
                or (s == "NEW-KEY" and a.cmd == "check")}
    too_few = len(qualified) < MIN_HOSTS
    if too_few:
        sys.stdout.flush()  # keep the row report above this line when piped
        print("pins: QUALIFIED %d minimum %d (NTX_SHARE_MIN_TRACKERS)"
              % (len(qualified), MIN_HOSTS), file=sys.stderr)

    if a.cmd == "update" and not blocking:
        if apply_update(rows, results):
            sys.stdout.write(write_table(a.trackers, src, tab_a, tab_b, rows))
            sys.stdout.write(write_pins_txt(a.pins_txt, rows))
    return 1 if (blocking or too_few) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
